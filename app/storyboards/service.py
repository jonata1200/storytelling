async def _image_provider_for_project(
    session: AsyncSession, project_id: UUID
) -> tuple[ImageProvider, str, str]:
    app_settings = get_settings()
    production_settings = await get_or_create_production_settings(session, project_id)
    model = resolve_image_model(
        production_settings.image_model,
        app_settings.openrouter_image_model,
    )
    ensure_openrouter_api_key(app_settings.openrouter_api_key)
    return OpenRouterImageProvider(), model, "openrouter_storyboards"


async def _create_artifact(
    session: AsyncSession,
    project_id: UUID,
    artifact_type: ArtifactType,
    name: str,
    payload: dict,
    status: ArtifactStatus = ArtifactStatus.READY_FOR_REVIEW,
) -> Artifact:
    artifact = Artifact(
        project_id=project_id,
        artifact_type=artifact_type,
        name=name,
        status=status,
    )
    session.add(artifact)
    await session.flush()
    session.add(
        ArtifactVersion(
            artifact_id=artifact.id,
            version_number=1,
            payload=payload,
            change_note="Generated by phase 5 storyboard workflow",
        )
    )
    await session.flush()
    return artifact


async def _add_dependency(session: AsyncSession, upstream: UUID, downstream: UUID) -> None:
    result = await session.execute(
        select(ArtifactDependency.id).where(
            ArtifactDependency.upstream_artifact_id == upstream,
            ArtifactDependency.downstream_artifact_id == downstream,
            ArtifactDependency.dependency_kind == DependencyKind.DERIVED_FROM,
        )
    )
    if result.scalar_one_or_none() is not None:
        return
    session.add(
        ArtifactDependency(
            upstream_artifact_id=upstream,
            downstream_artifact_id=downstream,
            dependency_kind=DependencyKind.DERIVED_FROM,
        )
    )


async def _ordered_shots_for_script(
    session: AsyncSession, project_id: UUID, script_id: UUID
) -> list[tuple[Shot, Scene]]:
    scene_artifact = aliased(Artifact)
    shot_artifact = aliased(Artifact)
    result = await session.execute(
        select(Shot, Scene)
        .join(Scene, Shot.scene_id == Scene.id)
        .join(scene_artifact, scene_artifact.id == Scene.artifact_id)
        .join(shot_artifact, shot_artifact.id == Shot.artifact_id)
        .where(Shot.project_id == project_id, Scene.script_id == script_id)
        .where(scene_artifact.status != ArtifactStatus.STALE)
        .where(shot_artifact.status != ArtifactStatus.STALE)
        .order_by(Scene.scene_number, Shot.shot_number)
    )
    return [(row[0], row[1]) for row in result.all()]


async def _selected_storyboard_shots(
    session: AsyncSession,
    project_id: UUID,
    script_id: UUID,
    scene_number: int | None = None,
) -> tuple[list[tuple[Shot, Scene]], list[tuple[Shot, Scene]], dict[UUID, int]]:
    all_shot_rows = await _ordered_shots_for_script(session, project_id, script_id)
    if not all_shot_rows:
        raise ValueError(
            "Nenhum plano encontrado para este roteiro. Gere as cenas e planos antes do storyboard."
        )
    shot_rows = all_shot_rows
    if scene_number is not None:
        shot_rows = [
            (shot, scene) for shot, scene in all_shot_rows if scene.scene_number == scene_number
        ]
        if not shot_rows:
            raise ValueError(f"Nenhum plano encontrado para a cena {scene_number}.")
    frame_number_by_shot = {
        shot.id: frame_number for frame_number, (shot, _scene) in enumerate(all_shot_rows, start=1)
    }
    return all_shot_rows, shot_rows, frame_number_by_shot


async def list_storyboard_prompt_previews(
    session: AsyncSession,
    project_id: UUID,
    script_id: UUID,
    scene_number: int | None = None,
) -> list[dict]:
    project = await ProjectRepository(session).get_project(project_id)
    script = await session.get(Script, script_id)
    if project is None or script is None or script.project_id != project_id:
        return []
    try:
        _all_shot_rows, shot_rows, frame_number_by_shot = await _selected_storyboard_shots(
            session,
            project_id,
            script_id,
            scene_number=scene_number,
        )
    except ValueError:
        return []
    production_settings = await get_or_create_production_settings(session, project_id)
    metadata = production_settings.metadata_json or {}
    visual_context = await _storyboard_visual_context(session, project_id)
    existing_frames = await list_storyboard_frames(session, project_id, script_id)
    existing_by_shot = {frame.shot_id: frame for frame in existing_frames}
    previews: list[dict] = []
    for shot, scene in shot_rows:
        prompt = _storyboard_prompt(shot, scene, visual_context)
        prompt_hash = _prompt_hash(prompt)
        previews.append(
            {
                "shot_id": shot.id,
                "scene_id": scene.id,
                "scene_number": scene.scene_number,
                "shot_number": shot.shot_number,
                "frame_number": frame_number_by_shot[shot.id],
                "duration_seconds": shot.duration_seconds,
                "prompt": prompt,
                "prompt_hash": prompt_hash,
                "approved": _storyboard_prompt_is_approved(
                    metadata,
                    script_id,
                    shot.id,
                    prompt_hash,
                ),
                "generated": shot.id in existing_by_shot,
            }
        )
    return previews


async def approve_storyboard_prompts(
    session: AsyncSession,
    project_id: UUID,
    script_id: UUID,
    scene_number: int | None = None,
) -> int:
    previews = await list_storyboard_prompt_previews(
        session,
        project_id,
        script_id,
        scene_number=scene_number,
    )
    if not previews:
        return 0
    production_settings = await get_or_create_production_settings(session, project_id)
    metadata = production_settings.metadata_json or {}
    approved_count = 0
    for preview in previews:
        if preview["approved"]:
            continue
        metadata = _store_storyboard_prompt_approval(
            metadata,
            script_id,
            preview["shot_id"],
            preview["prompt_hash"],
        )
        approved_count += 1
    production_settings.metadata_json = metadata
    await session.commit()
    return approved_count


async def storyboard_prompts_need_approval(
    session: AsyncSession,
    project_id: UUID,
    script_id: UUID,
    scene_number: int | None = None,
) -> bool:
    previews = await list_storyboard_prompt_previews(
        session,
        project_id,
        script_id,
        scene_number=scene_number,
    )
    if not previews:
        return True
    return any(not preview["approved"] for preview in previews)


async def _ensure_storyboard_prompts_approved(
    session: AsyncSession,
    project_id: UUID,
    script_id: UUID,
    shot_rows: list[tuple[Shot, Scene]],
    visual_context: dict,
) -> dict[UUID, str]:
    production_settings = await get_or_create_production_settings(session, project_id)
    metadata = production_settings.metadata_json or {}
    prompt_by_shot: dict[UUID, str] = {}
    pending: list[str] = []
    for shot, scene in shot_rows:
        prompt = _storyboard_prompt(shot, scene, visual_context)
        prompt_by_shot[shot.id] = prompt
        if not _storyboard_prompt_is_approved(
            metadata,
            script_id,
            shot.id,
            _prompt_hash(prompt),
        ):
            pending.append(f"cena {scene.scene_number}, plano {shot.shot_number}")
    if pending:
        sample = "; ".join(pending[:5])
        if len(pending) > 5:
            sample += f"; e mais {len(pending) - 5}"
        raise ValueError(
            f"Aprove os prompts de storyboard antes de gerar imagens. Pendentes: {sample}."
        )
    return prompt_by_shot


def storyboard_coverage_errors(
    shot_rows: list[tuple[Shot, Scene]], frames: list[StoryboardFrame]
) -> list[str]:
    errors: list[str] = []
    expected_shot_ids = [shot.id for shot, _scene in shot_rows]
    frame_by_shot = {frame.shot_id: frame for frame in frames}
    missing = [shot_id for shot_id in expected_shot_ids if shot_id not in frame_by_shot]
    if missing:
        errors.append(f"{len(missing)} plano(s) sem frame de storyboard")
    if len(frame_by_shot) != len(frames):
        errors.append("frames duplicados para o mesmo plano")
    expected_duration = sum(shot.duration_seconds for shot, _scene in shot_rows)
    actual_duration = sum(frame.duration_seconds for frame in frames)
    if expected_duration != actual_duration:
        errors.append(
            f"duracao dos frames ({actual_duration}s) difere dos planos ({expected_duration}s)"
        )
    expected_order = expected_shot_ids
    actual_order = [frame.shot_id for frame in sorted(frames, key=lambda item: item.frame_number)]
    if actual_order != expected_order:
        errors.append("ordem dos frames nao segue cena/plano")
    for frame in frames:
        if frame.asset_id is None:
            errors.append(f"frame {frame.frame_number} sem asset")
        if len(str(frame.prompt or "").split()) < 10:
            errors.append(f"frame {frame.frame_number} com prompt generico")
    return errors


async def generate_storyboard_frames(
    session: AsyncSession,
    project_id: UUID,
    script_id: UUID,
    scene_number: int | None = None,
    force: bool = False,
) -> list[StoryboardFrame] | None:
    project = await ProjectRepository(session).get_project(project_id)
    script = await session.get(Script, script_id)
    if project is None or script is None or script.project_id != project_id:
        return None

    visual_report = await visual_reference_completion_report(session, project_id)
    if not visual_report["complete"]:
        raise ValueError(visual_reference_completion_message(visual_report))

    all_shot_rows, shot_rows, frame_number_by_shot = await _selected_storyboard_shots(
        session,
        project_id,
        script_id,
        scene_number=scene_number,
    )

    provider, image_model, image_dir_name = await _image_provider_for_project(session, project_id)
    production_settings = await get_or_create_production_settings(session, project_id)
    image_resolution = production_settings.image_resolution
    output_dir = get_settings().local_storage_path / image_dir_name / str(project_id)
    visual_context = await _storyboard_visual_context(session, project_id)
    prompt_by_shot = await _ensure_storyboard_prompts_approved(
        session,
        project_id,
        script_id,
        shot_rows,
        visual_context,
    )
    existing_frames = await list_storyboard_frames(session, project_id, script_id)
    existing_by_shot = {frame.shot_id: frame for frame in existing_frames}
    frames: list[StoryboardFrame] = []

    for shot, scene in shot_rows:
        frame_number = frame_number_by_shot[shot.id]
        prompt = prompt_by_shot[shot.id]
        existing_frame = existing_by_shot.get(shot.id)
        existing_prompt_hash = (
            (existing_frame.metadata_json or {}).get("prompt_hash")
            if existing_frame is not None
            else None
        )
        existing_asset_available = await _storyboard_frame_asset_available(session, existing_frame)
        needs_image = (
            force
            or existing_frame is None
            or existing_prompt_hash != _prompt_hash(prompt)
            or not existing_asset_available
        )
        if needs_image:
            generation_started_at = perf_counter()
            image, fallback_metadata = await _generate_image_with_provider_fallback(
                provider,
                ImageGenerationRequest(
                    prompt=prompt,
                    target_id=str(shot.id),
                    view_type=f"storyboard_{frame_number:03d}",
                    output_dir=output_dir,
                    resolution=image_resolution,
                    model=image_model,
                ),
            )
            duration_ms = max(1, int((perf_counter() - generation_started_at) * 1000))
            generation_metadata = {
                "resolution": image_resolution,
                "duration_ms": duration_ms,
                **fallback_metadata,
            }
            asset_artifact_id = (
                existing_frame.artifact_id if existing_frame is not None else shot.artifact_id
            )
            asset = Asset(
                project_id=project_id,
                artifact_id=asset_artifact_id,
                kind=AssetKind.IMAGE,
                name=f"Storyboard frame {frame_number:03d}",
                storage_uri=image.storage_uri,
                content_type=image.content_type,
                sha256=image.sha256,
                metadata_json={
                    "provider": image.provider,
                    "model": image.model,
                    **generation_metadata,
                },
            )
            session.add(asset)
            await session.flush()
            session.add(
                AssetVersion(
                    asset_id=asset.id,
                    version_number=1,
                    storage_uri=asset.storage_uri,
                    sha256=asset.sha256,
                    metadata_json=asset.metadata_json,
                )
            )
            asset_id = asset.id
        else:
            assert existing_frame is not None
            image = None
            asset = None
            asset_id = existing_frame.asset_id
            duration_ms = None
            generation_metadata = {"reused": True}

        payload = _storyboard_frame_payload(scene, shot, asset_id, prompt)
        if existing_frame is not None:
            previous_fingerprint = (existing_frame.metadata_json or {}).get("frame_fingerprint")
            existing_frame.frame_number = frame_number
            existing_frame.duration_seconds = shot.duration_seconds
            existing_frame.prompt = prompt
            existing_frame.narration_text = shot.narration_text
            existing_frame.dialogue_text = shot.dialogue_text
            existing_frame.metadata_json = payload
            metadata_changed = previous_fingerprint != payload["frame_fingerprint"]
            if needs_image:
                existing_frame.asset_id = asset_id
                artifact = await session.get(Artifact, existing_frame.artifact_id)
                if artifact is not None:
                    artifact.name = f"Storyboard {scene.scene_number}.{shot.shot_number}"
                    await create_artifact_version(
                        session,
                        artifact,
                        payload,
                        change_note="Storyboard frame regenerated after prompt change",
                    )
                session.add(
                    PromptExecution(
                        project_id=project_id,
                        artifact_id=existing_frame.artifact_id,
                        prompt_template_id=None,
                        template_version=None,
                        provider=image.provider if image is not None else "reused",
                        model=image.model if image is not None else image_model,
                        prompt=prompt,
                        variables={"shot_id": str(shot.id), "scene_id": str(scene.id)},
                        response={
                            "asset_id": str(asset_id),
                            "storage_uri": asset.storage_uri if asset is not None else "",
                        },
                        parameters={"reused": False, **generation_metadata},
                        estimated_cost=(
                            Decimal(image.estimated_cost)
                            if image is not None
                            else Decimal("0.000000")
                        ),
                        duration_ms=duration_ms,
                    )
                )
            elif metadata_changed:
                artifact = await session.get(Artifact, existing_frame.artifact_id)
                if artifact is not None:
                    artifact.name = f"Storyboard {scene.scene_number}.{shot.shot_number}"
                    await create_artifact_version(
                        session,
                        artifact,
                        payload,
                        change_note="Storyboard frame metadata updated",
                    )
            else:
                artifact = await session.get(Artifact, existing_frame.artifact_id)
                if artifact is not None and artifact.name != (
                    f"Storyboard {scene.scene_number}.{shot.shot_number}"
                ):
                    artifact.name = f"Storyboard {scene.scene_number}.{shot.shot_number}"
            await _add_dependency(session, shot.artifact_id, existing_frame.artifact_id)
            frame = existing_frame
        else:
            artifact = await _create_artifact(
                session,
                project_id,
                ArtifactType.STORYBOARD,
                f"Storyboard {scene.scene_number}.{shot.shot_number}",
                payload,
            )
            await _add_dependency(session, shot.artifact_id, artifact.id)
            session.add(
                PromptExecution(
                    project_id=project_id,
                    artifact_id=artifact.id,
                    prompt_template_id=None,
                    template_version=None,
                    provider=image.provider if image is not None else "reused",
                    model=image.model if image is not None else image_model,
                    prompt=prompt,
                    variables={"shot_id": str(shot.id), "scene_id": str(scene.id)},
                    response={
                        "asset_id": str(asset_id),
                        "storage_uri": asset.storage_uri if asset is not None else "",
                    },
                    parameters={"reused": False, **generation_metadata},
                    estimated_cost=(
                        Decimal(image.estimated_cost) if image is not None else Decimal("0.000000")
                    ),
                    duration_ms=duration_ms,
                )
            )
            frame = StoryboardFrame(
                project_id=project_id,
                artifact_id=artifact.id,
                shot_id=shot.id,
                asset_id=asset_id,
                frame_number=frame_number,
                duration_seconds=shot.duration_seconds,
                prompt=prompt,
                narration_text=shot.narration_text,
                dialogue_text=shot.dialogue_text,
                metadata_json=payload,
            )
            session.add(frame)
        frames.append(frame)

    errors = storyboard_coverage_errors(shot_rows, frames)
    if errors:
        raise ValueError("Storyboard incompleto: " + "; ".join(errors))
    if scene_number is None:
        advance_project_status(project, ProjectStatus.STORYBOARD_APPROVAL)
    else:
        full_frames = await list_storyboard_frames(session, project_id, script_id)
        full_frame_by_shot = {frame.shot_id: frame for frame in full_frames}
        for frame in frames:
            full_frame_by_shot[frame.shot_id] = frame
        if not storyboard_coverage_errors(all_shot_rows, list(full_frame_by_shot.values())):
            advance_project_status(project, ProjectStatus.STORYBOARD_APPROVAL)
    await session.commit()
    for frame in frames:
        await session.refresh(frame)
    return frames


async def list_storyboard_frames(
    session: AsyncSession, project_id: UUID, script_id: UUID | None = None
) -> list[StoryboardFrame]:
    project = await ProjectRepository(session).get_project(project_id)
    if project is None:
        return []
    statement = (
        select(StoryboardFrame)
        .where(StoryboardFrame.project_id == project_id)
        .order_by(StoryboardFrame.frame_number)
    )
    if script_id is not None:
        statement = (
            select(StoryboardFrame)
            .join(Shot, StoryboardFrame.shot_id == Shot.id)
            .join(Scene, Shot.scene_id == Scene.id)
            .where(StoryboardFrame.project_id == project_id, Scene.script_id == script_id)
            .order_by(StoryboardFrame.frame_number)
        )
    result = await session.execute(statement)
    return list(result.scalars())


async def storyboard_frames_need_generation(
    session: AsyncSession,
    project_id: UUID,
    script_id: UUID,
) -> bool:
    shot_rows = await _ordered_shots_for_script(session, project_id, script_id)
    if not shot_rows:
        return True
    existing_frames = await list_storyboard_frames(session, project_id, script_id)
    if len(existing_frames) != len(shot_rows):
        return True
    existing_by_shot = {frame.shot_id: frame for frame in existing_frames}
    visual_context = await _storyboard_visual_context(session, project_id)
    for shot, scene in shot_rows:
        frame = existing_by_shot.get(shot.id)
        if frame is None:
            return True
        prompt = _storyboard_prompt(shot, scene, visual_context)
        existing_prompt_hash = (frame.metadata_json or {}).get("prompt_hash")
        if existing_prompt_hash != _prompt_hash(prompt):
            return True
        if not await _storyboard_frame_asset_available(session, frame):
            return True
    return False


async def delete_storyboard_outputs(session: AsyncSession, project_id: UUID) -> dict[str, int]:
    frame_rows = await session.execute(
        select(StoryboardFrame.id, StoryboardFrame.artifact_id, StoryboardFrame.asset_id).where(
            StoryboardFrame.project_id == project_id
        )
    )
    frame_data = list(frame_rows.all())
    frame_ids = [row[0] for row in frame_data]
    storyboard_artifact_ids = [row[1] for row in frame_data]
    asset_ids = {row[2] for row in frame_data if row[2] is not None}

    clip_rows = await session.execute(
        select(VideoClip.id, VideoClip.artifact_id, VideoClip.asset_id, VideoClip.generation_job_id)
        .where(VideoClip.project_id == project_id)
        .where(VideoClip.storyboard_frame_id.in_(frame_ids) if frame_ids else False)
    )
    clip_data = list(clip_rows.all())
    clip_ids = [row[0] for row in clip_data]
    video_artifact_ids = [row[1] for row in clip_data]
    asset_ids.update(row[2] for row in clip_data if row[2] is not None)
    generation_job_ids = [row[3] for row in clip_data if row[3] is not None]

    animatic_rows = await session.execute(
        select(Animatic.id, Animatic.artifact_id, Animatic.audio_track_id).where(
            Animatic.project_id == project_id
        )
    )
    animatic_data = list(animatic_rows.all())
    animatic_ids = [row[0] for row in animatic_data]
    animatic_artifact_ids = [row[1] for row in animatic_data]
    audio_track_ids = [row[2] for row in animatic_data if row[2] is not None]

    timeline_rows = await session.execute(
        select(Timeline.id, Timeline.artifact_id)
        .where(Timeline.project_id == project_id)
        .where(Timeline.animatic_id.in_(animatic_ids) if animatic_ids else False)
    )
    timeline_data = list(timeline_rows.all())
    timeline_ids = [row[0] for row in timeline_data]
    timeline_artifact_ids = [row[1] for row in timeline_data]

    audio_rows = await session.execute(
        select(AudioTrack.artifact_id).where(
            AudioTrack.id.in_(audio_track_ids) if audio_track_ids else False
        )
    )
    audio_artifact_ids = [row[0] for row in audio_rows.all()]

    artifact_ids = set(
        storyboard_artifact_ids
        + video_artifact_ids
        + animatic_artifact_ids
        + timeline_artifact_ids
        + audio_artifact_ids
    )

    if artifact_ids:
        asset_rows = await session.execute(
            select(Asset.id).where(
                Asset.project_id == project_id,
                Asset.artifact_id.in_(artifact_ids),
            )
        )
        asset_ids.update(row[0] for row in asset_rows.all())
    asset_storage_uris: list[str] = []
    if asset_ids:
        storage_rows = await session.execute(
            select(Asset.storage_uri).where(
                Asset.project_id == project_id,
                Asset.id.in_(asset_ids),
            )
        )
        asset_storage_uris = [str(row[0] or "") for row in storage_rows.all()]

    if clip_ids:
        await session.execute(delete(ClipReview).where(ClipReview.video_clip_id.in_(clip_ids)))
        await session.execute(delete(VideoClip).where(VideoClip.id.in_(clip_ids)))
    if timeline_ids:
        await session.execute(
            delete(TimelineItem).where(TimelineItem.timeline_id.in_(timeline_ids))
        )
        await session.execute(delete(Timeline).where(Timeline.id.in_(timeline_ids)))
    if animatic_ids:
        await session.execute(delete(Animatic).where(Animatic.id.in_(animatic_ids)))
    if audio_track_ids:
        await session.execute(delete(AudioTrack).where(AudioTrack.id.in_(audio_track_ids)))
    if frame_ids:
        await session.execute(delete(StoryboardFrame).where(StoryboardFrame.id.in_(frame_ids)))
    if generation_job_ids:
        await session.execute(delete(GenerationJob).where(GenerationJob.id.in_(generation_job_ids)))
    if asset_ids:
        await session.execute(delete(AssetVersion).where(AssetVersion.asset_id.in_(asset_ids)))
        await session.execute(delete(Asset).where(Asset.id.in_(asset_ids)))
    if artifact_ids:
        await session.execute(
            delete(PromptExecution).where(PromptExecution.artifact_id.in_(artifact_ids))
        )
        await session.execute(
            delete(ArtifactDependency).where(
                (ArtifactDependency.upstream_artifact_id.in_(artifact_ids))
                | (ArtifactDependency.downstream_artifact_id.in_(artifact_ids))
            )
        )
        await session.execute(
            delete(ArtifactVersion).where(ArtifactVersion.artifact_id.in_(artifact_ids))
        )
        await session.execute(delete(Artifact).where(Artifact.id.in_(artifact_ids)))
    deleted_files = sum(
        1 for storage_uri in asset_storage_uris if _delete_local_storage_file(storage_uri)
    )
    await session.commit()
    return {
        "frames": len(frame_ids),
        "clips": len(clip_ids),
        "animatics": len(animatic_ids),
        "timelines": len(timeline_ids),
        "assets": len(asset_ids),
        "artifacts": len(artifact_ids),
        "files": deleted_files,
    }


async def _create_provisional_narration(
    session: AsyncSession, project_id: UUID, frames: list[StoryboardFrame]
) -> AudioTrack:
    transcript = " ".join(
        frame.narration_text for frame in frames if frame.narration_text.strip()
    ).strip()
    duration_seconds = sum(frame.duration_seconds for frame in frames)
    alignment = build_word_alignment(transcript, duration_seconds)
    artifact = await _create_artifact(
        session,
        project_id,
        ArtifactType.AUDIO_TRACK,
        "Narracao provisoria",
        {"transcript": transcript, "alignment": alignment, "duration_seconds": duration_seconds},
    )
    track = AudioTrack(
        project_id=project_id,
        artifact_id=artifact.id,
        name="Narracao provisoria",
        track_type="provisional_narration",
        duration_seconds=duration_seconds,
        transcript=transcript,
        alignment=alignment,
    )
    session.add(track)
    return track


def _animatic_frame_signature(frames: list[StoryboardFrame]) -> list[dict]:
    return [
        {
            "frame_id": str(frame.id),
            "asset_id": str(frame.asset_id),
            "duration_seconds": frame.duration_seconds,
            "frame_fingerprint": (frame.metadata_json or {}).get("frame_fingerprint")
            or _prompt_hash(
                json.dumps(
                    {
                        "shot_id": str(frame.shot_id),
                        "duration_seconds": frame.duration_seconds,
                        "narration_text": frame.narration_text,
                        "dialogue_text": frame.dialogue_text,
                        "prompt": frame.prompt,
                    },
                    sort_keys=True,
                    ensure_ascii=True,
                )
            ),
        }
        for frame in sorted(frames, key=lambda item: item.frame_number)
    ]


def _animatic_fingerprint(frames: list[StoryboardFrame]) -> str:
    return _prompt_hash(
        json.dumps(_animatic_frame_signature(frames), sort_keys=True, ensure_ascii=True)
    )


async def _existing_animatic_bundle(
    session: AsyncSession, project_id: UUID, fingerprint: str
) -> tuple[AudioTrack, Animatic, Timeline, list[TimelineItem]] | None:
    result = await session.execute(
        select(Animatic)
        .where(Animatic.project_id == project_id)
        .order_by(Animatic.created_at.desc())
    )
    for animatic in result.scalars():
        if (animatic.manifest or {}).get("frames_fingerprint") != fingerprint:
            continue
        if animatic.audio_track_id is None:
            continue
        audio_track = await session.get(AudioTrack, animatic.audio_track_id)
        timeline_result = await session.execute(
            select(Timeline)
            .where(Timeline.project_id == project_id, Timeline.animatic_id == animatic.id)
            .order_by(Timeline.created_at.desc())
            .limit(1)
        )
        timeline = timeline_result.scalars().first()
        if audio_track is None or timeline is None:
            continue
        item_result = await session.execute(
            select(TimelineItem)
            .where(TimelineItem.timeline_id == timeline.id)
            .order_by(TimelineItem.order_index)
        )
        return audio_track, animatic, timeline, list(item_result.scalars())
    return None


async def generate_animatic_bundle(
    session: AsyncSession, project_id: UUID, script_id: UUID
) -> tuple[AudioTrack, Animatic, Timeline, list[TimelineItem]] | None:
    project = await ProjectRepository(session).get_project(project_id)
    script = await session.get(Script, script_id)
    if project is None or script is None or script.project_id != project_id:
        return None

    frames = await list_storyboard_frames(session, project_id, script_id)
    if not frames:
        frames = await generate_storyboard_frames(session, project_id, script_id) or []
    if not frames:
        return None

    frames_fingerprint = _animatic_fingerprint(frames)
    existing_bundle = await _existing_animatic_bundle(session, project_id, frames_fingerprint)
    if existing_bundle is not None:
        return existing_bundle

    audio_track = await _create_provisional_narration(session, project_id, frames)
    await session.flush()

    visual_inputs = [
        (
            frame.artifact_id,
            frame.asset_id,
            frame.duration_seconds,
            {"frame_id": str(frame.id), "motion": "slow_push_in"},
        )
        for frame in frames
    ]
    draft_items = build_visual_timeline_items(visual_inputs)
    duration_seconds = max(item.end_ms for item in draft_items) // 1000
    manifest = {
        "version": 1,
        "duration_seconds": duration_seconds,
        "frames_fingerprint": frames_fingerprint,
        "frames": [
            {
                "frame_id": str(frame.id),
                "asset_id": str(frame.asset_id),
                "duration_seconds": frame.duration_seconds,
                "narration_text": frame.narration_text,
                "frame_fingerprint": (frame.metadata_json or {}).get("frame_fingerprint"),
            }
            for frame in frames
        ],
        "audio_track_id": str(audio_track.id),
    }

    settings = get_settings()
    manifest_dir = settings.local_storage_path / "animatics" / str(project_id)
    manifest_dir.mkdir(parents=True, exist_ok=True)
    manifest_path = manifest_dir / f"animatic_{uuid4().hex[:8]}.json"
    manifest_path.write_text(json.dumps(manifest, indent=2, ensure_ascii=True), encoding="utf-8")

    animatic_artifact = await _create_artifact(
        session,
        project_id,
        ArtifactType.ANIMATIC,
        "Animatic preliminar",
        manifest,
    )
    await _add_dependency(session, audio_track.artifact_id, animatic_artifact.id)
    for frame in frames:
        await _add_dependency(session, frame.artifact_id, animatic_artifact.id)

    manifest_asset = Asset(
        project_id=project_id,
        artifact_id=animatic_artifact.id,
        kind=AssetKind.DOCUMENT,
        name="Animatic manifest",
        storage_uri=manifest_path.as_posix(),
        content_type="application/json",
        sha256=None,
        metadata_json={"kind": "animatic_manifest"},
    )
    session.add(manifest_asset)
    await session.flush()
    session.add(
        AssetVersion(
            asset_id=manifest_asset.id,
            version_number=1,
            storage_uri=manifest_asset.storage_uri,
            sha256=manifest_asset.sha256,
            metadata_json=manifest_asset.metadata_json,
        )
    )

    animatic = Animatic(
        project_id=project_id,
        artifact_id=animatic_artifact.id,
        audio_track_id=audio_track.id,
        name="Animatic preliminar",
        duration_seconds=duration_seconds,
        manifest=manifest,
    )
    session.add(animatic)
    await session.flush()

    timeline_artifact = await _create_artifact(
        session,
        project_id,
        ArtifactType.TIMELINE,
        "Timeline preliminar",
        {"animatic_id": str(animatic.id), "duration_seconds": duration_seconds},
    )
    await _add_dependency(session, animatic_artifact.id, timeline_artifact.id)
    timeline = Timeline(
        project_id=project_id,
        artifact_id=timeline_artifact.id,
        animatic_id=animatic.id,
        name="Timeline preliminar",
        duration_seconds=duration_seconds,
        profile={"aspect_ratio": "9:16", "resolution": "1080x1920", "fps": 30},
    )
    session.add(timeline)
    await session.flush()

    items: list[TimelineItem] = []
    for draft in draft_items:
        item = TimelineItem(
            timeline_id=timeline.id,
            project_id=project_id,
            source_artifact_id=draft.source_artifact_id,
            source_asset_id=draft.source_asset_id,
            layer=draft.layer,
            start_ms=draft.start_ms,
            end_ms=draft.end_ms,
            order_index=draft.order_index,
            properties=draft.properties,
        )
        session.add(item)
        items.append(item)

    audio_item = TimelineItem(
        timeline_id=timeline.id,
        project_id=project_id,
        source_artifact_id=audio_track.artifact_id,
        source_asset_id=None,
        layer="audio",
        start_ms=0,
        end_ms=duration_seconds * 1000,
        order_index=len(items) + 1,
        properties={"track_type": audio_track.track_type},
    )
    session.add(audio_item)
    items.append(audio_item)

    advance_project_status(project, ProjectStatus.PRODUCTION_PLANNING)
    await session.commit()
    await session.refresh(audio_track)
    await session.refresh(animatic)
    await session.refresh(timeline)
    for item in items:
        await session.refresh(item)
    return audio_track, animatic, timeline, items
