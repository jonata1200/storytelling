async def _image_provider_for_project(
    session: AsyncSession, project_id: UUID
) -> tuple[ImageProvider, str, str]:
    app_settings = get_settings()
    production_settings = await get_or_create_production_settings(session, project_id)
    model = production_settings.image_model or app_settings.openrouter_image_model
    if app_settings.openrouter_api_key and model != "mock-image":
        return OpenRouterImageProvider(), model, "openrouter_storyboards"
    return MockImageProvider(), "mock-image", "mock_storyboards"


async def _create_artifact(
    session: AsyncSession,
    project_id: UUID,
    artifact_type: ArtifactType,
    name: str,
    payload: dict,
    status: ArtifactStatus = ArtifactStatus.READY_FOR_REVIEW,
) -> Artifact:
    artifact = Artifact(
        project_id=project_id,
        artifact_type=artifact_type,
        name=name,
        status=status,
    )
    session.add(artifact)
    await session.flush()
    session.add(
        ArtifactVersion(
            artifact_id=artifact.id,
            version_number=1,
            payload=payload,
            change_note="Generated by phase 5 storyboard workflow",
        )
    )
    await session.flush()
    return artifact


async def _add_dependency(session: AsyncSession, upstream: UUID, downstream: UUID) -> None:
    session.add(
        ArtifactDependency(
            upstream_artifact_id=upstream,
            downstream_artifact_id=downstream,
            dependency_kind=DependencyKind.DERIVED_FROM,
        )
    )


async def _ordered_shots_for_script(
    session: AsyncSession, project_id: UUID, script_id: UUID
) -> list[tuple[Shot, Scene]]:
    result = await session.execute(
        select(Shot, Scene)
        .join(Scene, Shot.scene_id == Scene.id)
        .where(Shot.project_id == project_id, Scene.script_id == script_id)
        .order_by(Scene.scene_number, Shot.shot_number)
    )
    return [(row[0], row[1]) for row in result.all()]


def _storyboard_prompt(shot: Shot, scene: Scene) -> str:
    return (
        f"Storyboard frame for scene {scene.scene_number}, shot {shot.shot_number}. "
        f"Action: {shot.action}. Emotion: {shot.emotion}. "
        f"Composition: {shot.visual_composition}. Camera: {shot.camera_movement}. "
        "Vertical 9:16 cinematic storyboard, clear staging, consistent characters."
    )


async def generate_storyboard_frames(
    session: AsyncSession, project_id: UUID, script_id: UUID
) -> list[StoryboardFrame] | None:
    project = await ProjectRepository(session).get_project(project_id)
    script = await session.get(Script, script_id)
    if project is None or script is None or script.project_id != project_id:
        return None

    shot_rows = await _ordered_shots_for_script(session, project_id, script_id)
    if not shot_rows:
        return []

    provider, image_model, image_dir_name = await _image_provider_for_project(session, project_id)
    output_dir = get_settings().local_storage_path / image_dir_name / str(project_id)
    frames: list[StoryboardFrame] = []

    for frame_number, (shot, scene) in enumerate(shot_rows, start=1):
        prompt = _storyboard_prompt(shot, scene)
        image = await provider.generate(
            ImageGenerationRequest(
                prompt=prompt,
                target_id=str(shot.id),
                view_type=f"storyboard_{frame_number:03d}",
                output_dir=output_dir,
                model=image_model,
            )
        )
        asset = Asset(
            project_id=project_id,
            artifact_id=shot.artifact_id,
            kind=AssetKind.IMAGE,
            name=f"Storyboard frame {frame_number:03d}",
            storage_uri=image.storage_uri,
            content_type=image.content_type,
            sha256=image.sha256,
            metadata_json={"provider": image.provider, "model": image.model},
        )
        session.add(asset)
        await session.flush()
        session.add(
            AssetVersion(
                asset_id=asset.id,
                version_number=1,
                storage_uri=asset.storage_uri,
                sha256=asset.sha256,
                metadata_json=asset.metadata_json,
            )
        )
        payload = {
            "scene_number": scene.scene_number,
            "shot_number": shot.shot_number,
            "shot_id": str(shot.id),
            "asset_id": str(asset.id),
            "duration_seconds": shot.duration_seconds,
            "prompt": prompt,
        }
        artifact = await _create_artifact(
            session,
            project_id,
            ArtifactType.STORYBOARD,
            f"Storyboard {scene.scene_number}.{shot.shot_number}",
            payload,
        )
        await _add_dependency(session, shot.artifact_id, artifact.id)
        session.add(
            PromptExecution(
                project_id=project_id,
                artifact_id=artifact.id,
                prompt_template_id=None,
                template_version=None,
                provider=image.provider,
                model=image.model,
                prompt=prompt,
                variables={"shot_id": str(shot.id), "scene_id": str(scene.id)},
                response={"asset_id": str(asset.id), "storage_uri": asset.storage_uri},
                parameters={},
                estimated_cost=Decimal("0.000000"),
                duration_ms=None,
            )
        )
        frame = StoryboardFrame(
            project_id=project_id,
            artifact_id=artifact.id,
            shot_id=shot.id,
            asset_id=asset.id,
            frame_number=frame_number,
            duration_seconds=shot.duration_seconds,
            prompt=prompt,
            narration_text=shot.narration_text,
            dialogue_text=shot.dialogue_text,
            metadata_json=payload,
        )
        session.add(frame)
        frames.append(frame)

    advance_project_status(project, ProjectStatus.STORYBOARD_APPROVAL)
    await session.commit()
    for frame in frames:
        await session.refresh(frame)
    return frames


async def list_storyboard_frames(
    session: AsyncSession, project_id: UUID, script_id: UUID | None = None
) -> list[StoryboardFrame]:
    project = await ProjectRepository(session).get_project(project_id)
    if project is None:
        return []
    statement = (
        select(StoryboardFrame)
        .where(StoryboardFrame.project_id == project_id)
        .order_by(StoryboardFrame.frame_number)
    )
    if script_id is not None:
        statement = (
            select(StoryboardFrame)
            .join(Shot, StoryboardFrame.shot_id == Shot.id)
            .join(Scene, Shot.scene_id == Scene.id)
            .where(StoryboardFrame.project_id == project_id, Scene.script_id == script_id)
            .order_by(StoryboardFrame.frame_number)
        )
    result = await session.execute(statement)
    return list(result.scalars())


async def _create_provisional_narration(
    session: AsyncSession, project_id: UUID, frames: list[StoryboardFrame]
) -> AudioTrack:
    transcript = " ".join(
        frame.narration_text for frame in frames if frame.narration_text.strip()
    ).strip()
    duration_seconds = sum(frame.duration_seconds for frame in frames)
    alignment = build_word_alignment(transcript, duration_seconds)
    artifact = await _create_artifact(
        session,
        project_id,
        ArtifactType.AUDIO_TRACK,
        "Narracao provisoria",
        {"transcript": transcript, "alignment": alignment, "duration_seconds": duration_seconds},
    )
    track = AudioTrack(
        project_id=project_id,
        artifact_id=artifact.id,
        name="Narracao provisoria",
        track_type="provisional_narration",
        duration_seconds=duration_seconds,
        transcript=transcript,
        alignment=alignment,
    )
    session.add(track)
    return track


async def generate_animatic_bundle(
    session: AsyncSession, project_id: UUID, script_id: UUID
) -> tuple[AudioTrack, Animatic, Timeline, list[TimelineItem]] | None:
    project = await ProjectRepository(session).get_project(project_id)
    script = await session.get(Script, script_id)
    if project is None or script is None or script.project_id != project_id:
        return None

    frames = await list_storyboard_frames(session, project_id, script_id)
    if not frames:
        frames = await generate_storyboard_frames(session, project_id, script_id) or []
    if not frames:
        return None

    audio_track = await _create_provisional_narration(session, project_id, frames)
    await session.flush()

    visual_inputs = [
        (
            frame.artifact_id,
            frame.asset_id,
            frame.duration_seconds,
            {"frame_id": str(frame.id), "motion": "slow_push_in"},
        )
        for frame in frames
    ]
    draft_items = build_visual_timeline_items(visual_inputs)
    duration_seconds = max(item.end_ms for item in draft_items) // 1000
    manifest = {
        "version": 1,
        "duration_seconds": duration_seconds,
        "frames": [
            {
                "frame_id": str(frame.id),
                "asset_id": str(frame.asset_id),
                "duration_seconds": frame.duration_seconds,
                "narration_text": frame.narration_text,
            }
            for frame in frames
        ],
        "audio_track_id": str(audio_track.id),
    }

    settings = get_settings()
    manifest_dir = settings.local_storage_path / "animatics" / str(project_id)
    manifest_dir.mkdir(parents=True, exist_ok=True)
    manifest_path = manifest_dir / f"animatic_{uuid4().hex[:8]}.json"
    manifest_path.write_text(json.dumps(manifest, indent=2, ensure_ascii=True), encoding="utf-8")

    animatic_artifact = await _create_artifact(
        session,
        project_id,
        ArtifactType.ANIMATIC,
        "Animatic preliminar",
        manifest,
    )
    await _add_dependency(session, audio_track.artifact_id, animatic_artifact.id)
    for frame in frames:
        await _add_dependency(session, frame.artifact_id, animatic_artifact.id)

    manifest_asset = Asset(
        project_id=project_id,
        artifact_id=animatic_artifact.id,
        kind=AssetKind.DOCUMENT,
        name="Animatic manifest",
        storage_uri=manifest_path.as_posix(),
        content_type="application/json",
        sha256=None,
        metadata_json={"kind": "animatic_manifest"},
    )
    session.add(manifest_asset)
    await session.flush()
    session.add(
        AssetVersion(
            asset_id=manifest_asset.id,
            version_number=1,
            storage_uri=manifest_asset.storage_uri,
            sha256=manifest_asset.sha256,
            metadata_json=manifest_asset.metadata_json,
        )
    )

    animatic = Animatic(
        project_id=project_id,
        artifact_id=animatic_artifact.id,
        audio_track_id=audio_track.id,
        name="Animatic preliminar",
        duration_seconds=duration_seconds,
        manifest=manifest,
    )
    session.add(animatic)
    await session.flush()

    timeline_artifact = await _create_artifact(
        session,
        project_id,
        ArtifactType.TIMELINE,
        "Timeline preliminar",
        {"animatic_id": str(animatic.id), "duration_seconds": duration_seconds},
    )
    await _add_dependency(session, animatic_artifact.id, timeline_artifact.id)
    timeline = Timeline(
        project_id=project_id,
        artifact_id=timeline_artifact.id,
        animatic_id=animatic.id,
        name="Timeline preliminar",
        duration_seconds=duration_seconds,
        profile={"aspect_ratio": "9:16", "resolution": "1080x1920", "fps": 30},
    )
    session.add(timeline)
    await session.flush()

    items: list[TimelineItem] = []
    for draft in draft_items:
        item = TimelineItem(
            timeline_id=timeline.id,
            project_id=project_id,
            source_artifact_id=draft.source_artifact_id,
            source_asset_id=draft.source_asset_id,
            layer=draft.layer,
            start_ms=draft.start_ms,
            end_ms=draft.end_ms,
            order_index=draft.order_index,
            properties=draft.properties,
        )
        session.add(item)
        items.append(item)

    audio_item = TimelineItem(
        timeline_id=timeline.id,
        project_id=project_id,
        source_artifact_id=audio_track.artifact_id,
        source_asset_id=None,
        layer="audio",
        start_ms=0,
        end_ms=duration_seconds * 1000,
        order_index=len(items) + 1,
        properties={"track_type": audio_track.track_type},
    )
    session.add(audio_item)
    items.append(audio_item)

    advance_project_status(project, ProjectStatus.PRODUCTION_PLANNING)
    await session.commit()
    await session.refresh(audio_track)
    await session.refresh(animatic)
    await session.refresh(timeline)
    for item in items:
        await session.refresh(item)
    return audio_track, animatic, timeline, items
