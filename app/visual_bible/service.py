async def _image_provider_for_project(
    session: AsyncSession, project_id: UUID
) -> tuple[ImageProvider, str, str]:
    app_settings = get_settings()
    production_settings = await get_or_create_production_settings(session, project_id)
    model = production_settings.image_model or app_settings.openrouter_image_model
    if app_settings.openrouter_api_key and model != "mock-image":
        return OpenRouterImageProvider(), model, "openrouter_images"
    return MockImageProvider(), "mock-image", "mock_images"


async def _create_artifact(
    session: AsyncSession,
    project_id: UUID,
    artifact_type: ArtifactType,
    name: str,
    payload: dict,
) -> Artifact:
    artifact = Artifact(
        project_id=project_id,
        artifact_type=artifact_type,
        name=name,
        status=ArtifactStatus.READY_FOR_REVIEW,
    )
    session.add(artifact)
    await session.flush()
    session.add(
        ArtifactVersion(
            artifact_id=artifact.id,
            version_number=1,
            payload=payload,
            change_note="Generated by phase 4 visual bible workflow",
        )
    )
    await session.flush()
    return artifact


async def _add_dependency(session: AsyncSession, upstream: UUID, downstream: UUID) -> None:
    session.add(
        ArtifactDependency(
            upstream_artifact_id=upstream,
            downstream_artifact_id=downstream,
            dependency_kind=DependencyKind.DERIVED_FROM,
        )
    )


def _fingerprint(payload: dict) -> dict:
    canonical = json.dumps(payload, sort_keys=True, ensure_ascii=True)
    return {
        "schema_version": 1,
        "sha256": hashlib.sha256(canonical.encode("utf-8")).hexdigest(),
        "canonical_prompt": payload.get("canonical_prompt", ""),
        "reference_asset_ids": [],
    }


def _profile_items(value: object) -> list[dict]:
    if value is None:
        return []
    if isinstance(value, list):
        return [_profile_mapping(item) for item in value]
    if isinstance(value, dict):
        if any(key in value for key in ("name", "nome", "title", "titulo", "description")):
            return [_profile_mapping(value)]
        return [_profile_mapping(item) for item in value.values()]
    return [_profile_mapping(value)]


def _profile_mapping(raw: object) -> dict:
    if isinstance(raw, dict):
        normalized = dict(raw)
        if "name" not in normalized:
            normalized["name"] = (
                normalized.get("nome")
                or normalized.get("title")
                or normalized.get("titulo")
            )
        return normalized
    text = str(raw or "").strip()
    return {"name": text or "Item", "description": text}


def _short_text(value: object, fallback: str, max_length: int) -> str:
    text = str(value or fallback).strip() or fallback
    if len(text) <= max_length:
        return text
    if max_length <= 3:
        return text[:max_length]
    return f"{text[: max_length - 3].rstrip()}..."


