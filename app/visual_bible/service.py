async def generate_visual_bible(
    session: AsyncSession, project_id: UUID, story_bible_id: UUID
) -> tuple[list[Character], list[Location], list[Prop]] | None:
    project = await ProjectRepository(session).get_project(project_id)
    story_bible = await session.get(StoryBible, story_bible_id)
    if project is None or story_bible is None or story_bible.project_id != project_id:
        return None

    characters: list[Character] = []
    for raw in story_bible.payload.get("characters", []):
        profile = _character_profile(raw)
        artifact = await _create_artifact(
            session, project_id, ArtifactType.CHARACTER, profile["name"], profile
        )
        await _add_dependency(session, story_bible.artifact_id, artifact.id)
        character = Character(
            project_id=project_id,
            artifact_id=artifact.id,
            name=profile["name"],
            role=profile["role"],
            canonical_profile=profile,
            character_fingerprint=_fingerprint(profile),
        )
        session.add(character)
        await session.flush()
        session.add(
            CharacterVersion(
                character_id=character.id,
                version_number=1,
                canonical_profile=profile,
                change_note="Initial canonical character profile",
            )
        )
        characters.append(character)

    locations: list[Location] = []
    for raw in story_bible.payload.get("locations", []):
        profile = _location_profile(raw)
        artifact = await _create_artifact(
            session, project_id, ArtifactType.LOCATION, profile["name"], profile
        )
        await _add_dependency(session, story_bible.artifact_id, artifact.id)
        location = Location(
            project_id=project_id,
            artifact_id=artifact.id,
            name=profile["name"],
            description=profile["description"],
            canonical_profile=profile,
        )
        session.add(location)
        await session.flush()
        session.add(
            LocationVersion(
                location_id=location.id,
                version_number=1,
                canonical_profile=profile,
                change_note="Initial canonical location profile",
            )
        )
        locations.append(location)

    props: list[Prop] = []
    for raw in story_bible.payload.get("props", []):
        profile = _prop_profile(raw)
        artifact = await _create_artifact(
            session, project_id, ArtifactType.PROP, profile["name"], profile
        )
        await _add_dependency(session, story_bible.artifact_id, artifact.id)
        prop = Prop(
            project_id=project_id,
            artifact_id=artifact.id,
            name=profile["name"],
            narrative_importance=profile["narrative_importance"],
            canonical_profile=profile,
        )
        session.add(prop)
        await session.flush()
        session.add(
            PropVersion(
                prop_id=prop.id,
                version_number=1,
                canonical_profile=profile,
                change_note="Initial canonical prop profile",
            )
        )
        props.append(prop)

    await session.commit()
    for item in [*characters, *locations, *props]:
        await session.refresh(item)
    return characters, locations, props


async def _get_visual_target(
    session: AsyncSession, project_id: UUID, target_kind: str, target_id: UUID
) -> tuple[dict, UUID] | None:
    target: Character | Location | Prop | None
    if target_kind == "character":
        target = await session.get(Character, target_id)
    elif target_kind == "location":
        target = await session.get(Location, target_id)
    else:
        target = await session.get(Prop, target_id)
    if target is None or target.project_id != project_id:
        return None
    return target.canonical_profile, target.artifact_id


def default_views_for(target_kind: str) -> list[str]:
    return {
        "character": CHARACTER_VIEWS,
        "location": LOCATION_VIEWS,
        "prop": PROP_VIEWS,
    }[target_kind]


async def generate_visual_references(
    session: AsyncSession,
    project_id: UUID,
    target_kind: str,
    target_id: UUID,
    view_types: list[str] | None = None,
) -> list[VisualReference] | None:
    project = await ProjectRepository(session).get_project(project_id)
    if project is None:
        return None
    target = await _get_visual_target(session, project_id, target_kind, target_id)
    if target is None:
        return None
    profile, target_artifact_id = target
    settings = get_settings()
    provider = MockImageProvider()
    views = view_types or default_views_for(target_kind)
    references: list[VisualReference] = []
    output_dir = settings.local_storage_path / "mock_images" / str(project_id)

    for view_type in views:
        prompt = f"{profile.get('canonical_prompt', profile.get('name'))}. View: {view_type}."
        image_result = await provider.generate(
            ImageGenerationRequest(
                prompt=prompt,
                target_id=str(target_id),
                view_type=view_type,
                output_dir=output_dir,
            )
        )
        asset = Asset(
            project_id=project_id,
            artifact_id=target_artifact_id,
            kind=AssetKind.IMAGE,
            name=f"{profile.get('name', target_kind)} - {view_type}",
            storage_uri=image_result.storage_uri,
            content_type=image_result.content_type,
            sha256=image_result.sha256,
            metadata_json={"provider": image_result.provider, "model": image_result.model},
        )
        session.add(asset)
        await session.flush()
        session.add(
            AssetVersion(
                asset_id=asset.id,
                version_number=1,
                storage_uri=asset.storage_uri,
                sha256=asset.sha256,
                metadata_json=asset.metadata_json,
            )
        )
        reference_payload = {
            "target_kind": target_kind,
            "target_id": str(target_id),
            "view_type": view_type,
            "prompt": prompt,
            "asset_id": str(asset.id),
        }
        artifact = await _create_artifact(
            session,
            project_id,
            ArtifactType.VISUAL_REFERENCE,
            f"{profile.get('name', target_kind)} - {view_type}",
            reference_payload,
        )
        await _add_dependency(session, target_artifact_id, artifact.id)
        execution = PromptExecution(
            project_id=project_id,
            artifact_id=artifact.id,
            prompt_template_id=None,
            template_version=None,
            provider=image_result.provider,
            model=image_result.model,
            prompt=prompt,
            variables={"target_kind": target_kind, "target_id": str(target_id), "view": view_type},
            response={"asset_id": str(asset.id), "storage_uri": asset.storage_uri},
            parameters={},
            estimated_cost=Decimal("0.000000"),
            duration_ms=None,
        )
        session.add(execution)
        reference = VisualReference(
            project_id=project_id,
            artifact_id=artifact.id,
            asset_id=asset.id,
            target_kind=target_kind,
            target_id=target_id,
            view_type=view_type,
            prompt=prompt,
            provider=image_result.provider,
            model=image_result.model,
            metadata_json={"sha256": image_result.sha256},
        )
        session.add(reference)
        references.append(reference)

    await session.commit()
    for reference in references:
        await session.refresh(reference)
    return references


async def check_visual_consistency(
    session: AsyncSession, project_id: UUID, target_kind: str, target_id: UUID
) -> list[ConsistencyIssue] | None:
    project = await ProjectRepository(session).get_project(project_id)
    if project is None:
        return None
    target = await _get_visual_target(session, project_id, target_kind, target_id)
    if target is None:
        return None

    expected = set(default_views_for(target_kind))
    result = await session.execute(
        select(VisualReference.view_type).where(
            VisualReference.project_id == project_id,
            VisualReference.target_kind == target_kind,
            VisualReference.target_id == target_id,
        )
    )
    existing = set(result.scalars())
    missing = sorted(expected - existing)
    issues = [
        ConsistencyIssue(
            code="missing_visual_reference",
            message=f"Referencia visual ausente: {view_type}",
            severity="warning",
        )
        for view_type in missing
    ]
    return issues
