def _script_character_names(script_content: str) -> list[str]:
    names: list[str] = []
    seen: set[str] = set()
    for raw_line in script_content.splitlines():
        line = re.sub(r"\([^)]*\)", "", raw_line).strip(" .:-")
        if not line or len(line) > 48:
            continue
        if not re.fullmatch(r"[A-ZÁÉÍÓÚÂÊÔÃÕÇ ]{2,}", line):
            continue
        if line in SCRIPT_CHARACTER_EXCLUSIONS or line.startswith(("INT", "EXT")):
            continue
        key = line.lower()
        if key in seen:
            continue
        seen.add(key)
        names.append(line.title())
    return names


def _is_placeholder_profile_name(value: object) -> bool:
    text = str(value or "").strip().lower()
    return text in PLACEHOLDER_PROFILE_NAMES


def _repair_missing_character_names(
    items: list[dict], script_content: str, protagonist_hint: str = ""
) -> list[dict]:
    candidates = _script_character_names(script_content)
    missing_count = sum(1 for item in items if _is_placeholder_profile_name(item.get("name")))
    use_script_candidates = missing_count > 0 and len(candidates) >= missing_count
    candidate_index = 0
    repaired: list[dict] = []
    used_names: set[str] = set()
    for item in items:
        profile = dict(item)
        if _is_placeholder_profile_name(profile.get("name")):
            role = _first_value(profile, "role", "funcao", "função", fallback="")
            replacement = ""
            if protagonist_hint and _is_primary_protagonist_role(role):
                replacement = protagonist_hint
            elif use_script_candidates and candidate_index < len(candidates):
                replacement = candidates[candidate_index]
                candidate_index += 1
            else:
                replacement = _role_display_name(role)
            if replacement:
                profile["name"] = replacement
        name = str(profile.get("name") or "").strip()
        key = name.lower()
        if key and key in used_names:
            role_name = _role_display_name(_first_value(profile, "role", "funcao", "função"))
            if role_name and role_name.lower() != key:
                profile["name"] = role_name
                key = role_name.lower()
        if key:
            used_names.add(key)
        repaired.append(profile)
    return repaired


def _match_visual_target(
    existing: list[Character] | list[Location] | list[Prop], profile: dict
) -> Character | Location | Prop | None:
    identity = _visual_profile_identity(profile)
    name_key = _visual_key(profile.get("name"))
    for item in existing:
        item_profile = item.canonical_profile or {}
        if identity and _visual_profile_identity(item_profile) == identity:
            return item
        if name_key and _visual_key(item.name) == name_key:
            return item
    return None


async def _upsert_character_profile(
    session: AsyncSession,
    project_id: UUID,
    source_artifact_id: UUID,
    profile: dict,
    existing_characters: list[Character],
) -> Character:
    existing = _match_visual_target(existing_characters, profile)
    if isinstance(existing, Character):
        if _profile_sha256(existing.canonical_profile or {}) != _profile_sha256(profile):
            existing.name = str(profile["name"])
            existing.role = str(profile["role"])
            existing.canonical_profile = profile
            existing.character_fingerprint = _fingerprint(profile)
            existing.current_version += 1
            session.add(
                CharacterVersion(
                    character_id=existing.id,
                    version_number=existing.current_version,
                    canonical_profile=profile,
                    change_note="Canonical character profile updated from script",
                )
            )
            artifact = await session.get(Artifact, existing.artifact_id)
            if artifact is not None:
                artifact.name = existing.name
                await create_artifact_version(
                    session,
                    artifact,
                    profile,
                    change_note="Canonical character profile updated from script",
                )
        await _add_dependency(session, source_artifact_id, existing.artifact_id)
        return existing

    artifact = await _create_artifact(
        session, project_id, ArtifactType.CHARACTER, profile["name"], profile
    )
    await _add_dependency(session, source_artifact_id, artifact.id)
    character = Character(
        project_id=project_id,
        artifact_id=artifact.id,
        name=profile["name"],
        role=profile["role"],
        canonical_profile=profile,
        character_fingerprint=_fingerprint(profile),
    )
    session.add(character)
    await session.flush()
    session.add(
        CharacterVersion(
            character_id=character.id,
            version_number=1,
            canonical_profile=profile,
            change_note="Initial canonical character profile",
        )
    )
    existing_characters.append(character)
    return character


