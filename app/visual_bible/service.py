async def generate_visual_bible(
    session: AsyncSession, project_id: UUID, story_bible_id: UUID
) -> tuple[list[Character], list[Location], list[Prop]] | None:
    project = await ProjectRepository(session).get_project(project_id)
    story_bible = await session.get(StoryBible, story_bible_id)
    if project is None or story_bible is None or story_bible.project_id != project_id:
        return None

    characters: list[Character] = []
    for raw in _profile_items(story_bible.payload.get("characters")):
        profile = _character_profile(raw)
        artifact = await _create_artifact(
            session, project_id, ArtifactType.CHARACTER, profile["name"], profile
        )
        await _add_dependency(session, story_bible.artifact_id, artifact.id)
        character = Character(
            project_id=project_id,
            artifact_id=artifact.id,
            name=profile["name"],
            role=profile["role"],
            canonical_profile=profile,
            character_fingerprint=_fingerprint(profile),
        )
        session.add(character)
        await session.flush()
        session.add(
            CharacterVersion(
                character_id=character.id,
                version_number=1,
                canonical_profile=profile,
                change_note="Initial canonical character profile",
            )
        )
        characters.append(character)

    locations: list[Location] = []
    for raw in _profile_items(story_bible.payload.get("locations")):
        profile = _location_profile(raw)
        artifact = await _create_artifact(
            session, project_id, ArtifactType.LOCATION, profile["name"], profile
        )
        await _add_dependency(session, story_bible.artifact_id, artifact.id)
        location = Location(
            project_id=project_id,
            artifact_id=artifact.id,
            name=profile["name"],
            description=profile["description"],
            canonical_profile=profile,
        )
        session.add(location)
        await session.flush()
        session.add(
            LocationVersion(
                location_id=location.id,
                version_number=1,
                canonical_profile=profile,
                change_note="Initial canonical location profile",
            )
        )
        locations.append(location)

    props: list[Prop] = []
    for raw in _profile_items(story_bible.payload.get("props")):
        profile = _prop_profile(raw)
        artifact = await _create_artifact(
            session, project_id, ArtifactType.PROP, profile["name"], profile
        )
        await _add_dependency(session, story_bible.artifact_id, artifact.id)
        prop = Prop(
            project_id=project_id,
            artifact_id=artifact.id,
            name=profile["name"],
            narrative_importance=profile["narrative_importance"],
            canonical_profile=profile,
        )
        session.add(prop)
        await session.flush()
        session.add(
            PropVersion(
                prop_id=prop.id,
                version_number=1,
                canonical_profile=profile,
                change_note="Initial canonical prop profile",
            )
        )
        props.append(prop)

    await session.commit()
    for item in [*characters, *locations, *props]:
        await session.refresh(item)
    return characters, locations, props


async def _get_visual_target(
    session: AsyncSession, project_id: UUID, target_kind: str, target_id: UUID
) -> tuple[dict, UUID] | None:
    target: Character | Location | Prop | None
    if target_kind == "character":
        target = await session.get(Character, target_id)
    elif target_kind == "location":
        target = await session.get(Location, target_id)
    else:
        target = await session.get(Prop, target_id)
    if target is None or target.project_id != project_id:
        return None
    return target.canonical_profile, target.artifact_id


def default_views_for(target_kind: str) -> list[str]:
    return {
        "character": CHARACTER_VIEWS,
        "location": LOCATION_VIEWS,
        "prop": PROP_VIEWS,
    }[target_kind]


def initial_view_for(target_kind: str) -> str:
    return {
        "character": "front_portrait",
        "location": "establishing",
        "prop": "front",
    }[target_kind]


def visual_reference_prompt(profile: dict, view_type: str) -> str:
    base_prompt = str(profile.get("canonical_prompt") or profile.get("name") or "").strip()
    view_detail = VIEW_PROMPT_DETAILS.get(view_type, view_type.replace("_", " "))
    return (
        f"{base_prompt}. Reference view: {view_type}. {view_detail}. "
        "Vertical 9:16 production reference, clean background, consistent visual identity."
    )


async def update_visual_target_prompt(
    session: AsyncSession,
    project_id: UUID,
    target_kind: str,
    target_id: UUID,
    canonical_prompt: str,
    change_note: str | None = None,
) -> Character | Location | Prop | None:
    prompt = canonical_prompt.strip()
    if not prompt:
        raise ValueError("O prompt nao pode ficar vazio")

    target: Character | Location | Prop | None
    if target_kind == "character":
        target = await session.get(Character, target_id)
    elif target_kind == "location":
        target = await session.get(Location, target_id)
    elif target_kind == "prop":
        target = await session.get(Prop, target_id)
    else:
        return None
    if target is None or target.project_id != project_id:
        return None

    profile = dict(target.canonical_profile or {})
    if profile.get("canonical_prompt") == prompt:
        return target
    profile["canonical_prompt"] = prompt
    target.canonical_profile = profile
    target.current_version += 1

    if isinstance(target, Character):
        target.character_fingerprint = _fingerprint(profile)
        session.add(
            CharacterVersion(
                character_id=target.id,
                version_number=target.current_version,
                canonical_profile=profile,
                change_note=change_note or "Canonical prompt edited",
            )
        )
    elif isinstance(target, Location):
        session.add(
            LocationVersion(
                location_id=target.id,
                version_number=target.current_version,
                canonical_profile=profile,
                change_note=change_note or "Canonical prompt edited",
            )
        )
    else:
        session.add(
            PropVersion(
                prop_id=target.id,
                version_number=target.current_version,
                canonical_profile=profile,
                change_note=change_note or "Canonical prompt edited",
            )
        )

    artifact = await session.get(Artifact, target.artifact_id)
    if artifact is not None:
        artifact.status = ArtifactStatus.READY_FOR_REVIEW
        await create_artifact_version(
            session,
            artifact,
            profile,
            change_note=change_note or "Canonical visual prompt edited",
        )

    await session.commit()
    await session.refresh(target)
    return target


async def _existing_visual_reference_views(
    session: AsyncSession, project_id: UUID, target_kind: str, target_id: UUID
) -> set[str]:
    result = await session.execute(
        select(VisualReference.view_type).where(
            VisualReference.project_id == project_id,
            VisualReference.target_kind == target_kind,
            VisualReference.target_id == target_id,
        )
    )
    return set(result.scalars())


async def approve_visual_target_and_generate_views(
    session: AsyncSession,
    project_id: UUID,
    target_kind: str,
    target_id: UUID,
    view_types: list[str] | None = None,
) -> list[VisualReference] | None:
    project = await ProjectRepository(session).get_project(project_id)
    target = await _get_visual_target(session, project_id, target_kind, target_id)
    if project is None or target is None:
        return None

    _profile, target_artifact_id = target
    artifact = await session.get(Artifact, target_artifact_id)
    if artifact is None:
        return None
    version_result = await session.execute(
        select(ArtifactVersion)
        .where(
            ArtifactVersion.artifact_id == artifact.id,
            ArtifactVersion.version_number == artifact.current_version,
        )
        .limit(1)
    )
    artifact_version = version_result.scalars().first()
    if artifact_version is None:
        return None

    await record_approval(
        session,
        artifact,
        artifact_version,
        ApprovalDecision.APPROVED,
        notes="Perfil visual aprovado para criacao de vistas multiplas.",
    )
    existing_views = await _existing_visual_reference_views(
        session, project_id, target_kind, target_id
    )
    requested_views = view_types or default_views_for(target_kind)
    missing_views = [
        view for view in requested_views if view not in existing_views
    ]
    if not missing_views:
        await session.commit()
        return []
    return await generate_visual_references(
        session,
        project_id,
        target_kind,
        target_id,
        missing_views,
    )


async def generate_visual_references(
    session: AsyncSession,
    project_id: UUID,
    target_kind: str,
    target_id: UUID,
    view_types: list[str] | None = None,
    force: bool = False,
) -> list[VisualReference] | None:
    project = await ProjectRepository(session).get_project(project_id)
    if project is None:
        return None
    target = await _get_visual_target(session, project_id, target_kind, target_id)
    if target is None:
        return None
    profile, target_artifact_id = target
    provider, image_model, image_dir_name = await _image_provider_for_project(session, project_id)
    requested_views = view_types or default_views_for(target_kind)
    if force:
        views = requested_views
    else:
        existing_views = await _existing_visual_reference_views(
            session, project_id, target_kind, target_id
        )
        views = [view for view in requested_views if view not in existing_views]
    if not views:
        return []
    references: list[VisualReference] = []
    output_dir = get_settings().local_storage_path / image_dir_name / str(project_id)

    for view_type in views:
        prompt = visual_reference_prompt(profile, view_type)
        image_result = await provider.generate(
            ImageGenerationRequest(
                prompt=prompt,
                target_id=str(target_id),
                view_type=view_type,
                output_dir=output_dir,
                model=image_model,
            )
        )
        asset = Asset(
            project_id=project_id,
            artifact_id=target_artifact_id,
            kind=AssetKind.IMAGE,
            name=f"{profile.get('name', target_kind)} - {view_type}",
            storage_uri=image_result.storage_uri,
            content_type=image_result.content_type,
            sha256=image_result.sha256,
            metadata_json={"provider": image_result.provider, "model": image_result.model},
        )
        session.add(asset)
        await session.flush()
        session.add(
            AssetVersion(
                asset_id=asset.id,
                version_number=1,
                storage_uri=asset.storage_uri,
                sha256=asset.sha256,
                metadata_json=asset.metadata_json,
            )
        )
        reference_payload = {
            "target_kind": target_kind,
            "target_id": str(target_id),
            "view_type": view_type,
            "prompt": prompt,
            "asset_id": str(asset.id),
        }
        artifact = await _create_artifact(
            session,
            project_id,
            ArtifactType.VISUAL_REFERENCE,
            f"{profile.get('name', target_kind)} - {view_type}",
            reference_payload,
        )
        await _add_dependency(session, target_artifact_id, artifact.id)
        execution = PromptExecution(
            project_id=project_id,
            artifact_id=artifact.id,
            prompt_template_id=None,
            template_version=None,
            provider=image_result.provider,
            model=image_result.model,
            prompt=prompt,
            variables={"target_kind": target_kind, "target_id": str(target_id), "view": view_type},
            response={"asset_id": str(asset.id), "storage_uri": asset.storage_uri},
            parameters={},
            estimated_cost=Decimal("0.000000"),
            duration_ms=None,
        )
        session.add(execution)
        reference = VisualReference(
            project_id=project_id,
            artifact_id=artifact.id,
            asset_id=asset.id,
            target_kind=target_kind,
            target_id=target_id,
            view_type=view_type,
            prompt=prompt,
            provider=image_result.provider,
            model=image_result.model,
            metadata_json={"sha256": image_result.sha256},
        )
        session.add(reference)
        references.append(reference)

    await session.commit()
    for reference in references:
        await session.refresh(reference)
    return references


async def regenerate_visual_reference(
    session: AsyncSession,
    project_id: UUID,
    target_kind: str,
    target_id: UUID,
    view_type: str,
) -> VisualReference | None:
    references = await generate_visual_references(
        session,
        project_id,
        target_kind,
        target_id,
        [view_type],
        force=True,
    )
    if references is None:
        return None
    return references[0] if references else None


async def check_visual_consistency(
    session: AsyncSession, project_id: UUID, target_kind: str, target_id: UUID
) -> list[ConsistencyIssue] | None:
    project = await ProjectRepository(session).get_project(project_id)
    if project is None:
        return None
    target = await _get_visual_target(session, project_id, target_kind, target_id)
    if target is None:
        return None

    expected = set(default_views_for(target_kind))
    result = await session.execute(
        select(VisualReference.view_type).where(
            VisualReference.project_id == project_id,
            VisualReference.target_kind == target_kind,
            VisualReference.target_id == target_id,
        )
    )
    existing = set(result.scalars())
    missing = sorted(expected - existing)
    issues = [
        ConsistencyIssue(
            code="missing_visual_reference",
            message=f"Referencia visual ausente: {view_type}",
            severity="warning",
        )
        for view_type in missing
    ]
    return issues
